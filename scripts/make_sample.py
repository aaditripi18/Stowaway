"""Build the limits page's sample model as a script (web/public/samples/).

The pages may not fetch anything (connect-src 'none'), so the sample is shipped
as a same-origin script that defines its bytes, loaded only when the reader asks
for it. The model is fetched through stowaway.hub, so it is pinned to a commit
and checked against the Hub's SHA-256.

    python scripts/make_sample.py
"""
from __future__ import annotations

import base64
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from stowaway import hub  # noqa: E402

REPO, REV = "google/bert_uncased_L-2_H-128_A-2", "30b0a37ccaaa32f332884b96992754e246e48c5f"
OUT = ROOT / "web" / "public" / "samples"


def main() -> None:
    res = hub.resolve(f"hf:{REPO}@{REV}")
    (path,) = hub.download(res)
    data = path.read_bytes()
    OUT.mkdir(parents=True, exist_ok=True)
    meta = (f'{{"repo":"{REPO}","commit":"{res.commit}","file":"model.safetensors",'
            f'"sha256":"{res.sha256["model.safetensors"]}","bytes":{len(data)},"license":"Apache-2.0"}}')
    (OUT / "bert-L2-H128.js").write_text(
        "// Sample model for the limits page. Generated by scripts/make_sample.py; see NOTICE.txt.\n"
        f"self.STOWAWAY_SAMPLE = {{meta: {meta}, b64: \"{base64.b64encode(data).decode()}\"}};\n",
        encoding="ascii")
    (OUT / "NOTICE.txt").write_text(
        f"bert-L2-H128.js holds model.safetensors from {REPO}\n"
        f"(https://huggingface.co/{REPO}), commit {res.commit},\n"
        f"SHA-256 {res.sha256['model.safetensors']}, base64-encoded.\n"
        "Copyright Google. Licensed under the Apache License, Version 2.0\n"
        "(https://www.apache.org/licenses/LICENSE-2.0). Unmodified: the limits page\n"
        "plants random bytes only in a copy held in memory.\n", encoding="utf-8")
    print(f"wrote {OUT / 'bert-L2-H128.js'} ({len(data):,} bytes of model)")


if __name__ == "__main__":
    main()
